/**
 * quantize.js —— 跨引擎数值一致性工具。
 *
 * 背景（这是本项目一条硬约束，别绕过）：
 *   Math.sin / cos / log / exp 的输出在不同 V8 版本间**不保证一致**。
 *   实测 Math.sin(4π/3) 在 Chrome 152 上是 -0.86602540378443837454，
 *   在 Node 的 V8 14.6 上是 -0.86602540378443848557 —— 差 1~2 ULP，且只有
 *   12 个月份里有 1 个中招。
 *
 *   危害不在于误差小，而在于它会级联：只要特征值差 1 ULP，树模型的分裂条件
 *   （x <= threshold）就可能翻转，产生**结构不同的树**，误差不再小而是任意的。
 *   即使本项目不用树模型，纯线性模型上也会让「node 测试通过、浏览器结果不同」。
 *
 * 处理办法：只对超越函数的**输出**做 1e-12 量化（加减乘除是 IEEE-754 精确的，
 * 不需要也不能量化）。测试里既有「必须量化」的正向断言，也有「未量化值不满足
 * 该性质」的负向对照，防止有人把这段量化当冗余代码删掉。
 */

/** 量化到 1e-12：抹平跨引擎 ULP 差异，同时远小于任何有业务意义的差异。 */
export const q = (x) => Math.round(x * 1e12) / 1e12;

/** 某个数是否是 1e-12 的整数倍（供测试断言量化生效）。 */
export const isQuantized = (x) => Math.abs(x * 1e12 - Math.round(x * 1e12)) < 1e-6;
